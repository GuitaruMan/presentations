-- 고급 과학 4과목의 선수과목을 학교 규정대로 고친다 (2026-09-21)
--
-- 지금까지는 '고급 물리학 ← 물리학'처럼 일반선택 한 과목만 적혀 있었다.
-- 학교가 운영하는 규정은 일반선택 과목에 더해 진로선택 두 과목 중 하나를 먼저 듣는 것이다.
--
--   고급 물리학   ← 물리학   그리고 (역학과 에너지 · 전자기와 양자   중 1과목)
--   고급 화학     ← 화학     그리고 (화학 반응의 세계 · 물질과 에너지 중 1과목)
--   고급 생명과학 ← 생명과학 그리고 (세포와 물질대사 · 생물의 유전   중 1과목)
--   고급 지구과학 ← 지구과학 그리고 (지구시스템과학 · 행성우주과학   중 1과목)
--
-- 교육과정이 강제하는 것이 아니라 학교 자체 규정이다. 학생 화면은 담기를 막지 않고
-- '강력 권장' 경고로 알린다(Ⅰ/Ⅱ 짝만 담기를 막는다).
--
-- 적는 법: 선수 조건 한 칸은 과목 이름 하나(문자열)이거나 '그중 1과목'을 뜻하는 묶음(배열)이다.
-- 칸들 사이는 '그리고', 묶음 안은 '또는'. 이 모양은 app.js 20260921a 판부터 읽는다 —
-- 화면 파일을 먼저 올린 뒤에 이 SQL 을 실행할 것. (옛 화면은 묶음을 과목 이름으로 잘못 읽는다.)
--
-- 두 학년도(2026-g2, 2025-g3) 모두에 적용한다. 네 과목의 값만 바꾸고 나머지 12개 관계는 그대로 둔다.
-- 앞으로는 관리자 화면 → 이수규칙 → ⑤ 선수과목 관계의 [+ 그리고] [+ 또는] 으로 직접 고칠 수 있다.
--
-- 실행 방법: Supabase 대시보드 → SQL Editor 에 붙여넣고 실행.

UPDATE school_rules
SET 선수과목 = 선수과목 || '{
  "고급 물리학":   ["물리학",   ["역학과 에너지", "전자기와 양자"]],
  "고급 화학":     ["화학",     ["화학 반응의 세계", "물질과 에너지"]],
  "고급 생명과학": ["생명과학", ["세포와 물질대사", "생물의 유전"]],
  "고급 지구과학": ["지구과학", ["지구시스템과학", "행성우주과학"]]
}'::jsonb
WHERE cohort_id IN (
  SELECT id FROM school_cohorts WHERE 코호트id IN ('2026-g2', '2025-g3')
);

-- 확인용 — 두 줄이 나오고, 네 과목 모두 묶음이 들어 있어야 한다
SELECT c.코호트id,
       r.선수과목 -> '고급 물리학'   AS 고급물리학,
       r.선수과목 -> '고급 화학'     AS 고급화학,
       r.선수과목 -> '고급 생명과학' AS 고급생명과학,
       r.선수과목 -> '고급 지구과학' AS 고급지구과학
FROM school_rules r JOIN school_cohorts c ON c.id = r.cohort_id
ORDER BY c.id;
